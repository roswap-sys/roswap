// Package ofedprobe 扫描 OFED 与内核头文件，生成 rs_compat.h。
package ofedprobe

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"
)

// Flags 是 rs_compat.h 里的开关，取值为 0 或 1。
type Flags struct {
	ConnectLocked     int
	AckTimeout        int
	CreateIDNet       int
	IbAllocCQ         int
	IbProcessCQDirect int
	BlkAllocDisk      int
	IbAddInt          int
	RDMA              string
	Verbs             string
	BlkMQ             string
}

var ibAddReturn = regexp.MustCompile(`int[[:space:]]*\(\*add\)`)

// IncludeDirs 返回实际存在的头文件搜索目录。
func IncludeDirs(ofed, kdir string) []string {
	var dirs []string
	for _, dir := range []string{filepath.Join(ofed, "include"), filepath.Join(kdir, "include")} {
		st, err := os.Stat(dir)
		if err == nil && st.IsDir() {
			dirs = append(dirs, dir)
		}
	}
	return dirs
}

func findHdr(dirs []string, name string) string {
	for _, dir := range dirs {
		path := filepath.Join(dir, name)
		st, err := os.Stat(path)
		if err == nil && !st.IsDir() {
			return path
		}
	}
	return ""
}

func fileHas(path, sym string) bool {
	if path == "" {
		return false
	}
	body, err := os.ReadFile(path)
	if err != nil {
		return false
	}
	return strings.Contains(string(body), sym)
}

func bit(ok bool) int {
	if ok {
		return 1
	}
	return 0
}

// Scan 读取已经定位到的头文件内容。path 为空表示该头文件不存在。
func Scan(rdmaCM, ibVerbs, blkMQ string) Flags {
	f := Flags{RDMA: rdmaCM, Verbs: ibVerbs, BlkMQ: blkMQ}
	f.ConnectLocked = bit(fileHas(rdmaCM, "rdma_connect_locked"))
	f.AckTimeout = bit(fileHas(rdmaCM, "rdma_set_ack_timeout"))
	f.CreateIDNet = bit(fileHas(rdmaCM, "struct net"))
	f.IbAllocCQ = bit(fileHas(ibVerbs, "ib_alloc_cq"))
	f.IbProcessCQDirect = bit(fileHas(ibVerbs, "ib_process_cq_direct"))
	f.BlkAllocDisk = bit(fileHas(blkMQ, "blk_mq_alloc_disk"))
	f.IbAddInt = ibAddReturnsInt(ibVerbs)
	return f
}

func ibAddReturnsInt(path string) int {
	if path == "" {
		return 0
	}
	body, err := os.ReadFile(path)
	if err != nil {
		return 0
	}
	text := string(body)
	idx := strings.Index(text, "struct ib_client")
	if idx < 0 {
		return 0
	}
	lines := strings.Split(text[idx:], "\n")
	if len(lines) > 41 {
		lines = lines[:41]
	}
	if ibAddReturn.MatchString(strings.Join(lines, "\n")) {
		return 1
	}
	return 0
}

// ScanDirs 在 include 目录里查找 rdma_cm.h、ib_verbs.h 和 blk-mq.h。
func ScanDirs(dirs []string) Flags {
	return Scan(
		findHdr(dirs, filepath.Join("rdma", "rdma_cm.h")),
		findHdr(dirs, filepath.Join("rdma", "ib_verbs.h")),
		findHdr(dirs, filepath.Join("linux", "blk-mq.h")),
	)
}

// Render 生成 rs_compat.h。
func Render(f Flags) string {
	return fmt.Sprintf(`/* Generated by roswap probe. */
#ifndef _RS_COMPAT_H
#define _RS_COMPAT_H

#define RS_HAVE_RDMA_CONNECT_LOCKED %d
#define RS_HAVE_RDMA_SET_ACK_TIMEOUT %d
#define RS_RDMA_CREATE_ID_NET %d
#define RS_HAVE_IB_ALLOC_CQ %d
#define RS_HAVE_IB_PROCESS_CQ_DIRECT %d
#define RS_HAVE_BLK_MQ_ALLOC_DISK %d
#define RS_IB_ADD_RETURNS_INT %d

#endif
`, f.ConnectLocked, f.AckTimeout, f.CreateIDNet, f.IbAllocCQ, f.IbProcessCQDirect, f.BlkAllocDisk, f.IbAddInt)
}

// Probe 在找到头文件时覆盖 out，否则保留已有文件并返回说明。
func Probe(ofed, kdir, out string) (string, error) {
	dirs := IncludeDirs(ofed, kdir)
	if len(dirs) == 0 {
		return fmt.Sprintf("未找到头文件目录，保留已有的 rs_compat.h\n  OFED_DIR=%s\n  KDIR=%s", ofed, kdir), nil
	}
	flags := ScanDirs(dirs)
	if err := os.WriteFile(out, []byte(Render(flags)), 0644); err != nil {
		return "", err
	}
	rdma := flags.RDMA
	if rdma == "" {
		rdma = "缺失"
	}
	verbs := flags.Verbs
	if verbs == "" {
		verbs = "缺失"
	}
	blk := flags.BlkMQ
	if blk == "" {
		blk = "缺失"
	}
	return fmt.Sprintf("写入 %s\n  rdma_cm.h=%s connect_locked=%d ack_timeout=%d create_id_net=%d\n  ib_verbs.h=%s ib_alloc_cq=%d ib_process_cq_direct=%d\n  blk-mq.h=%s blk_mq_alloc_disk=%d ib_add_int=%d",
		out, rdma, flags.ConnectLocked, flags.AckTimeout, flags.CreateIDNet,
		verbs, flags.IbAllocCQ, flags.IbProcessCQDirect, blk, flags.BlkAllocDisk, flags.IbAddInt), nil
}
