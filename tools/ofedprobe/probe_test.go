package ofedprobe

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func TestProbeKeepsExistingWhenHeadersMissing(t *testing.T) {
	out := filepath.Join(t.TempDir(), "rs_compat.h")
	msg, err := Probe("/no/such/ofed", "/no/such/kdir", out)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(msg, "保留") {
		t.Fatalf("msg %q", msg)
	}
	if _, err := os.Stat(out); !os.IsNotExist(err) {
		t.Fatal("missing headers should not create rs_compat.h")
	}
}

func TestProbeWritesFlags(t *testing.T) {
	root := t.TempDir()
	ofed := filepath.Join(root, "ofed")
	write := func(rel, body string) {
		t.Helper()
		path := filepath.Join(ofed, "include", rel)
		if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(body), 0644); err != nil {
			t.Fatal(err)
		}
	}
	write("rdma/rdma_cm.h", "struct net;\nint rdma_connect_locked(void);\nint rdma_set_ack_timeout(void);\n")
	write("rdma/ib_verbs.h", "struct ib_client {\n  int (*add)(struct ib_device *);\n};\nint ib_alloc_cq(void);\nint ib_process_cq_direct(void);\n")
	write("linux/blk-mq.h", "struct request_queue;\n")
	out := filepath.Join(root, "rs_compat.h")
	msg, err := Probe(ofed, filepath.Join(root, "missing-kdir"), out)
	if err != nil {
		t.Fatal(err)
	}
	body, err := os.ReadFile(out)
	if err != nil {
		t.Fatal(err)
	}
	text := string(body)
	if !strings.Contains(text, "Generated by roswap probe.") {
		t.Fatalf("missing generated marker:\n%s", text)
	}
	wants := []string{
		"#define RS_HAVE_RDMA_CONNECT_LOCKED 1",
		"#define RS_HAVE_RDMA_SET_ACK_TIMEOUT 1",
		"#define RS_RDMA_CREATE_ID_NET 1",
		"#define RS_HAVE_IB_ALLOC_CQ 1",
		"#define RS_HAVE_IB_PROCESS_CQ_DIRECT 1",
		"#define RS_HAVE_BLK_MQ_ALLOC_DISK 0",
		"#define RS_IB_ADD_RETURNS_INT 1",
	}
	for _, want := range wants {
		if !strings.Contains(text, want) {
			t.Fatalf("missing %s in\n%s\nmsg %s", want, text, msg)
		}
	}
}

func TestIbAddVoid(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, "ib_verbs.h")
	body := "struct ib_client {\n  void (*add)(struct ib_device *);\n};\n"
	if err := os.WriteFile(path, []byte(body), 0644); err != nil {
		t.Fatal(err)
	}
	if got := ibAddReturnsInt(path); got != 0 {
		t.Fatalf("got %d", got)
	}
}
